"""Generate offline conversion data from the checked-in, pinned OpenCC dictionaries."""
from pathlib import Path

root = Path(__file__).resolve().parents[1]
source = root / 'third_party' / 'opencc'
output = root / 'lib' / 'lyrics' / 'generated' / 'chinese_dictionary.dart'
header = '''// Generated by scripts/generate_lyrics_dictionary.py. Do not edit.
// Dictionary data: OpenCC 1.1.9, Apache-2.0. See third_party/opencc/.
// Use the first preferred mapping; preserve phrase overrides for t2s.
'''
chunks = [header]
for name, variable in [('TSCharacters', 'traditionalToSimplifiedCharacters'),
                       ('TSPhrases', 'traditionalToSimplifiedPhrases'),
                       ('STCharacters', 'simplifiedToTraditionalCharacters')]:
    rows = []
    for line in (source / f'{name}.txt').read_text().splitlines():
        if not line or line.startswith('#'):
            continue
        key, values = line.split('\t')
        rows.append(key + '\t' + values.split(' ')[0])
    value = '\n'.join(rows)
    assert "'''" not in value
    chunks.append(f"const {variable} = r'''{value}''';\n")
license_text = (source / 'LICENSE').read_text()
chunks.append(f"const openCcLicense = r'''{license_text}''';\n")
output.write_text('\n'.join(chunks))
